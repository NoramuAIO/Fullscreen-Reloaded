export function t(key) {
  let lang = Settings.get("language") || "auto";
  if (lang === "auto") {
    const spLocale = SpotiKitBridge.getLocale() || "en";
    lang = spLocale.split("-")[0].toLowerCase();
  }
  const dict = Locales[lang] || Locales.en;
  return dict[key] || Locales.en[key] || key;
}
